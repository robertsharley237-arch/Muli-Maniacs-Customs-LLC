BEGIN;

CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(250) NOT NULL,
  sku VARCHAR(100) NOT NULL,
  price NUMERIC(10, 2) NOT NULL DEFAULT 0
    CHECK (price >= 0),
  image TEXT NOT NULL DEFAULT '',
  image_public_id VARCHAR(500) NOT NULL DEFAULT '',
  stock INTEGER NOT NULL DEFAULT 0
    CHECK (stock >= 0),
  variants JSONB NOT NULL DEFAULT '[]'::JSONB
    CHECK (jsonb_typeof(variants) = 'array'),
  low_stock_warning INTEGER NOT NULL DEFAULT 5
    CHECK (low_stock_warning >= 0),
  category VARCHAR(150) NOT NULL DEFAULT 'General',
  description TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS products_sku_lower_uidx
  ON products (LOWER(sku));

CREATE TABLE IF NOT EXISTS settings (
  id SMALLINT PRIMARY KEY DEFAULT 1
    CHECK (id = 1),
  store_name VARCHAR(200) NOT NULL
    DEFAULT 'Multi-Maniacs Customs LLC',
  contact_phone_1 VARCHAR(30) NOT NULL
    DEFAULT '(606)212-4695',
  contact_phone_2 VARCHAR(30) NOT NULL
    DEFAULT '(606)220-0185',
  contact_email VARCHAR(254) NOT NULL
    DEFAULT 'multimaniacscustoms@gmail.com',
  business_location VARCHAR(250) NOT NULL
    DEFAULT 'Essie, Kentucky',
  tax_rate NUMERIC(5, 2) NOT NULL DEFAULT 0
    CHECK (tax_rate >= 0 AND tax_rate <= 100),
  store_open BOOLEAN NOT NULL DEFAULT TRUE,
  closed_store_message VARCHAR(500) NOT NULL
    DEFAULT 'The online shop is temporarily unavailable. Please contact MMC for assistance.',
  default_stock INTEGER NOT NULL DEFAULT 0
    CHECK (default_stock >= 0),
  default_low_stock_warning INTEGER NOT NULL DEFAULT 5
    CHECK (default_low_stock_warning >= 0),
  auto_activate_products BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO settings (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

COMMIT;
