BEGIN;

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL DEFAULT '',
  subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0
    CHECK (subtotal >= 0),
  tax NUMERIC(12, 2) NOT NULL DEFAULT 0
    CHECK (tax >= 0),
  total NUMERIC(12, 2) NOT NULL DEFAULT 0
    CHECK (total >= 0),
  currency VARCHAR(3) NOT NULL DEFAULT 'USD'
    CHECK (currency ~ '^[A-Z]{3}$'),
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (
      status IN (
        'pending',
        'paid',
        'processing',
        'completed',
        'cancelled',
        'refunded'
      )
    ),
  payment_status VARCHAR(30) NOT NULL DEFAULT 'unpaid'
    CHECK (
      payment_status IN (
        'unpaid',
        'paid',
        'failed',
        'cancelled',
        'refunded',
        'partially_refunded'
      )
    ),
  stripe_session_id VARCHAR(300),
  stripe_payment_intent_id VARCHAR(300),
  stripe_customer_id VARCHAR(300),
  items JSONB NOT NULL DEFAULT '[]'::JSONB
    CHECK (jsonb_typeof(items) = 'array'),
  notes VARCHAR(2000) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ,
  refunded_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS orders_stripe_session_id_uidx
  ON orders (stripe_session_id)
  WHERE stripe_session_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS orders_stripe_payment_intent_id_uidx
  ON orders (stripe_payment_intent_id)
  WHERE stripe_payment_intent_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS orders_created_at_idx
  ON orders (created_at DESC);

CREATE INDEX IF NOT EXISTS orders_status_idx
  ON orders (status);

CREATE INDEX IF NOT EXISTS orders_payment_status_idx
  ON orders (payment_status);

CREATE INDEX IF NOT EXISTS orders_email_lower_idx
  ON orders (LOWER(email));

COMMIT;
