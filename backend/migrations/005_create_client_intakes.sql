BEGIN;

CREATE TABLE IF NOT EXISTS client_intakes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  email VARCHAR(254) NOT NULL,
  contact_method VARCHAR(50) NOT NULL DEFAULT '',
  project_type VARCHAR(150) NOT NULL,
  description VARCHAR(5000) NOT NULL,
  budget VARCHAR(100) NOT NULL DEFAULT '',
  timeline VARCHAR(150) NOT NULL DEFAULT '',
  location VARCHAR(250) NOT NULL DEFAULT '',
  image_url VARCHAR(2000) NOT NULL DEFAULT '',
  image_public_id VARCHAR(500) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'new'
    CHECK (
      status IN (
        'new',
        'contacted',
        'in_review',
        'approved',
        'closed'
      )
    ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS client_intakes_created_at_idx
  ON client_intakes (created_at DESC);

CREATE INDEX IF NOT EXISTS client_intakes_status_idx
  ON client_intakes (status);

CREATE INDEX IF NOT EXISTS client_intakes_email_lower_idx
  ON client_intakes (LOWER(email));

COMMIT;
